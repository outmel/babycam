"""
Download / export the on-device models into apps/mobile/assets/models.

    python models/fetch_models.py            # YAMNet + MediaPipe Pose (small downloads)
    python models/fetch_models.py --yolo     # also export YOLO11n to TFLite (needs `pip install ultralytics`)

Outputs:
    yolo11n.tflite          object detection, 320x320 float32 input, [1, 84, N] output
    pose_landmarks.tflite   MediaPipe Pose landmarker (lite), 256x256 float32 input
    yamnet.tflite           YAMNet audio classifier, 15600-sample (0.975 s @ 16 kHz) input
    yamnet_classes.json     index of the crying classes in YAMNet's 521 outputs
"""
from __future__ import annotations

import argparse
import csv
import io
import json
import shutil
import sys
import urllib.request
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "apps" / "mobile" / "assets" / "models"

YAMNET_URLS = [
    "https://storage.googleapis.com/download.tensorflow.org/models/tflite/task_library/audio_classification/android/lite-model_yamnet_classification_tflite_1.tflite",
    "https://tfhub.dev/google/lite-model/yamnet/classification/tflite/1?lite-format=tflite",
]
YAMNET_CLASSES_URL = "https://raw.githubusercontent.com/tensorflow/models/master/research/audioset/yamnet/yamnet_class_map.csv"
POSE_TASK_URL = "https://storage.googleapis.com/mediapipe-models/pose_landmarker/pose_landmarker_lite/float16/latest/pose_landmarker_lite.task"
CRY_CLASS_NAMES = ["Crying, sobbing", "Baby cry, infant cry"]


def fetch(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": "lulu-model-fetch"})
    with urllib.request.urlopen(req, timeout=120) as r:
        return r.read()


def fetch_yamnet() -> None:
    for url in YAMNET_URLS:
        try:
            data = fetch(url)
            if len(data) > 1_000_000:
                (OUT / "yamnet.tflite").write_bytes(data)
                print(f"yamnet.tflite  {len(data) / 1e6:.1f} MB  ({url.split('/')[2]})")
                break
        except Exception as e:  # noqa: BLE001 - try the next mirror
            print(f"  {url}: {e}")
    else:
        sys.exit("Could not download YAMNet")

    rows = list(csv.DictReader(io.StringIO(fetch(YAMNET_CLASSES_URL).decode("utf-8"))))
    idx = {r["display_name"]: int(r["index"]) for r in rows}
    cry = [idx[n] for n in CRY_CLASS_NAMES]
    (OUT / "yamnet_classes.json").write_text(json.dumps({"numClasses": len(rows), "cry": cry, "names": CRY_CLASS_NAMES}, indent=2))
    print(f"yamnet_classes.json  crying classes = {cry}")


def fetch_pose() -> None:
    task = fetch(POSE_TASK_URL)
    with zipfile.ZipFile(io.BytesIO(task)) as z:
        name = next(n for n in z.namelist() if "landmarks" in n and n.endswith(".tflite"))
        data = z.read(name)
    (OUT / "pose_landmarks.tflite").write_bytes(data)
    (ROOT / "harness" / "extract").mkdir(parents=True, exist_ok=True)
    (ROOT / "harness" / "extract" / "pose_landmarker_lite.task").write_bytes(task)
    print(f"pose_landmarks.tflite  {len(data) / 1e6:.1f} MB  (from {name})")


def export_yolo(imgsz: int) -> None:
    try:
        from ultralytics import YOLO
    except ImportError:
        sys.exit("YOLO export needs Ultralytics: pip install ultralytics")
    work = ROOT / "models" / ".work"
    work.mkdir(parents=True, exist_ok=True)
    model = YOLO(str(work / "yolo11n.pt") if (work / "yolo11n.pt").exists() else "yolo11n.pt")
    path = Path(model.export(format="tflite", imgsz=imgsz, half=False, int8=False, nms=False))
    tflite = path if path.suffix == ".tflite" else next(path.glob("*float32.tflite"))
    shutil.copy(tflite, OUT / "yolo11n.tflite")
    print(f"yolo11n.tflite  {tflite.stat().st_size / 1e6:.1f} MB  imgsz={imgsz}")


def write_asset_index() -> None:
    """Metro needs static require() calls, so generate the module that lists bundled models."""
    def entry(name: str, file: str) -> str:
        present = (OUT / file).exists()
        return f"  {name}: {'require' + repr('../../assets/models/' + file).replace(chr(39), chr(34)).join('()') if present else 'null'},"

    index = ROOT / "apps" / "mobile" / "src" / "vision" / "modelAssets.ts"
    index.write_text(
        "// Generated by models/fetch_models.py. A null entry means that model hasn't been fetched yet.\n"
        "export const MODEL_ASSETS: { yolo: number | null; pose: number | null; yamnet: number | null } = {\n"
        + "\n".join([entry("yolo", "yolo11n.tflite"), entry("pose", "pose_landmarks.tflite"), entry("yamnet", "yamnet.tflite")])
        + "\n};\n"
    )
    print(f"wrote {index.relative_to(ROOT)}")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--yolo", action="store_true", help="export YOLO11n to TFLite (needs ultralytics on Linux x86 or macOS)")
    ap.add_argument("--yolo-file", type=Path, help="install an already-exported yolo11n *_float32.tflite (e.g. from the GitHub Action)")
    ap.add_argument("--imgsz", type=int, default=320, help="YOLO input size; 320 runs well on older phones")
    ap.add_argument("--skip-downloads", action="store_true")
    args = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    if not args.skip_downloads:
        fetch_yamnet()
        fetch_pose()
    if args.yolo_file:
        shutil.copy(args.yolo_file, OUT / "yolo11n.tflite")
        print(f"installed {args.yolo_file} as yolo11n.tflite")
    elif args.yolo:
        export_yolo(args.imgsz)
    if not (OUT / "yolo11n.tflite").exists():
        print(
            "\nyolo11n.tflite is missing. Export it with the 'Export YOLO11n' GitHub Action (or --yolo on Linux/macOS),"
            "\nthen run: python models/fetch_models.py --skip-downloads --yolo-file path/to/yolo11n_float32.tflite"
        )
    write_asset_index()


if __name__ == "__main__":
    main()
